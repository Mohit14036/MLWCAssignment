"""Time-varying multipath channel models (tapped-delay-line, wide-sense stationary
uncorrelated scattering) evaluated on the 72 x 14 LTE time-frequency grid.

Channel time-frequency response (what the Vienna LTE simulator calls the "perfect channel"):

    H[k, l] = sum_p  sqrt(P_p) * g_p(t_l) * exp(-j 2 pi f_k tau_p)                      (1)

    f_k   : base-band frequency of sub-carrier k
    t_l   : centre of OFDM symbol l
    tau_p : delay of path p,  P_p : normalised power (sum_p P_p = 1  ->  E|H|^2 = 1)
    g_p   : unit-power Rayleigh fading process with the Jakes (Clarke) Doppler spectrum,
            generated by the sum-of-sinusoids method

    g_p(t) = 1/sqrt(M) * sum_{m=1..M} exp( j (2 pi f_D cos(alpha_m) t + phi_m) )         (2)

    alpha_m, phi_m ~ U[0, 2 pi)  (independent per path / realisation),  f_D = v f_c / c.

Power-delay profiles
--------------------
* ITU-R M.1225 Vehicular-A :  delays [0, 310, 710, 1090, 1730, 2510] ns,
                              powers [0, -1, -9, -10, -15, -20] dB
* SUI-5 (Erceg et al., IEEE 802.16.3c-01/29r4) : delays [0, 4, 10] us, powers [0, -5, -10] dB,
                              K-factor 0 (Rayleigh), standard Doppler [2.0, 1.5, 2.5] Hz
"""
from __future__ import annotations

import numpy as np

from .ofdm import OFDMGrid

SPEED_OF_LIGHT = 299_792_458.0

CHANNEL_PROFILES = {
    "VehA": {
        "delays_s": np.array([0.0, 310.0, 710.0, 1090.0, 1730.0, 2510.0]) * 1e-9,
        "powers_db": np.array([0.0, -1.0, -9.0, -10.0, -15.0, -20.0]),
        "standard_doppler_hz": None,
        "reference": "ITU-R M.1225 Vehicular-A",
    },
    "SUI5": {
        "delays_s": np.array([0.0, 4.0, 10.0]) * 1e-6,
        "powers_db": np.array([0.0, -5.0, -10.0]),
        "standard_doppler_hz": np.array([2.0, 1.5, 2.5]),
        "reference": "Erceg et al., SUI-5 (IEEE 802.16.3c-01/29r4)",
    },
}


def max_doppler_hz(speed_kmh: float, carrier_freq: float) -> float:
    """f_D = v * f_c / c."""
    return speed_kmh / 3.6 * carrier_freq / SPEED_OF_LIGHT


def path_parameters(name: str, ch_cfg: dict):
    """Return (delays [s], normalised linear powers, per-path max Doppler [Hz])."""
    if name not in CHANNEL_PROFILES:
        raise KeyError(f"unknown channel model {name}; available: {list(CHANNEL_PROFILES)}")
    prof = CHANNEL_PROFILES[name]
    tau = prof["delays_s"].astype(float)
    p = 10.0 ** (prof["powers_db"] / 10.0)
    p = p / p.sum()
    if ch_cfg.get("doppler_mode", "speed") == "standard" and prof["standard_doppler_hz"] is not None:
        fd = prof["standard_doppler_hz"].astype(float)
    else:
        fd = np.full(tau.shape, max_doppler_hz(float(ch_cfg["speed_kmh"]), float(ch_cfg["carrier_freq"])))
    return tau, p, fd


def rms_delay_spread(tau: np.ndarray, p: np.ndarray) -> float:
    m = np.sum(p * tau)
    return float(np.sqrt(np.sum(p * tau ** 2) - m ** 2))


def channel_summary(name: str, ch_cfg: dict, grid: OFDMGrid) -> dict:
    tau, p, fd = path_parameters(name, ch_cfg)
    trms = rms_delay_spread(tau, p)
    return {
        "model": name,
        "reference": CHANNEL_PROFILES[name]["reference"],
        "n_paths": len(tau),
        "max_delay_us": float(tau.max() * 1e6),
        "rms_delay_spread_us": trms * 1e6,
        "coherence_bw_kHz(1/(5*trms))": 1.0 / (5 * trms) / 1e3,
        "max_doppler_hz": float(fd.max()),
        "coherence_time_ms(0.423/fD)": 0.423 / fd.max() * 1e3,
        "cp_duration_us": min(grid.cp_lengths) / grid.fs * 1e6,
    }


def generate_tdl_channels(name: str, n: int, grid: OFDMGrid, ch_cfg: dict,
                          rng: np.random.Generator, batch: int = 2000) -> np.ndarray:
    """Generate ``n`` independent channel realisations H of shape (n, K, L), complex64, E|H|^2 = 1."""
    tau, p, fd = path_parameters(name, ch_cfg)
    M = int(ch_cfg.get("n_sinusoids", 32))
    f = grid.subcarrier_freqs                                     # (K,)
    t = grid.symbol_times                                         # (L,)
    E = np.exp(-2j * np.pi * np.outer(f, tau))                    # (K, P) delay -> phase ramp, eq. (1)
    K, L, P = len(f), len(t), len(tau)
    out = np.empty((n, K, L), dtype=np.complex64)
    for s in range(0, n, batch):
        b = min(batch, n - s)
        alpha = rng.uniform(0, 2 * np.pi, size=(b, P, M))         # angles of arrival
        phi = rng.uniform(0, 2 * np.pi, size=(b, P, M))           # random phases
        # eq. (2): phase[b, p, m, l] = 2 pi f_D,p cos(alpha) t_l + phi
        phase = (2 * np.pi * fd[None, :, None, None] * np.cos(alpha)[..., None] * t[None, None, None, :]
                 + phi[..., None])
        g = np.exp(1j * phase).sum(axis=2) / np.sqrt(M)           # (b, P, L) unit-power fading
        g *= np.sqrt(p)[None, :, None]
        out[s:s + b] = np.einsum("kp,bpl->bkl", E, g).astype(np.complex64)   # eq. (1)
    return out
